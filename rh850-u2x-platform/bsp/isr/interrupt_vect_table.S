 * @brief Interrupt vector table definition.
 *
 * @details
 * UC SUPPORT:
 *    RH850 U2x
 *
 *
 * Interrupt Vector Table
 *
 * The Interrupt Vector Table contains addresses (not instructions).
 * This file contains only default Interrupt Vector Tables. Users should define their own Interrupt Vector Tables to fit their application's needs.
 * There is a default Interrupt Vector Table for all PEs. All default Interrupt Vector Tables are identical.
 * All PEs will execute the same default interrupt service routine, which contains a simple never-ending loop.
 *
 *************************************************************************************************/


